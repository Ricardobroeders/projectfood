/** Fill `{n}` / `{m}` placeholders in a string. */
export function fmt(s: string, values: Record<string, number | string>): string {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in values ? String(values[k]) : `{${k}}`));
}
